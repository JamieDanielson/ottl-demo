#!/usr/bin/env python3
"""Builds the file-replay backup from the live kit.

Writes backup/replay/data/*.ndjson (one OTLP/JSON object per line, as the
otlp_json_file receiver requires) and backup/replay/config/<stage>.yaml, which is
each stage with the OTLP/HTTP receiver swapped for otlp_json_file.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = ROOT / "backup" / "replay"
RECEIVER = """receivers:
  otlp:
    protocols:
      http:
        endpoint: 0.0.0.0:4318
"""
REPLAY = """receivers:
  otlp_json_file:
    include: [/data/*.ndjson]
    start_at: beginning      # offsets live in memory: restart the container to replay
    include_file_name: false
"""

for sub in ("data", "config"):
    (HERE / sub).mkdir(exist_ok=True)
    # Generated output only: clear it so renamed or removed stages don't linger.
    for old in (HERE / sub).iterdir():
        old.unlink()
for f in sorted((ROOT / "data").glob("[0-9]-*.json")):
    (HERE / "data" / f"{f.stem}.ndjson").write_text(json.dumps(json.loads(f.read_text())) + "\n")
for f in sorted((ROOT / "config").glob("[0-9]*.yaml")):
    text = f.read_text()
    # The http endpoint line carries a trailing comment in 00-baseline only.
    text = text.replace("        endpoint: 0.0.0.0:4318   # in a container, localhost is unreachable from the host\n",
                        "        endpoint: 0.0.0.0:4318\n")
    if RECEIVER not in text:
        raise SystemExit(f"{f.name}: receiver block not in the expected shape")
    text = text.replace(RECEIVER, REPLAY).replace("receivers: [otlp]", "receivers: [otlp_json_file]")
    (HERE / "config" / f.name).write_text("# GENERATED by backup/replay/make_replay.py. Do not edit.\n" + text)
print(f"replay kit written to {HERE.relative_to(ROOT)}")
